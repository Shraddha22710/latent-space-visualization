from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from sklearn.decomposition import PCA
from sklearn.manifold import TSNE
from sklearn.neighbors import NearestNeighbors
from sklearn.preprocessing import StandardScaler
import umap


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results_canonical"
OUT.mkdir(exist_ok=True)


def lorenz(n=900, dt=0.01, discard=150):
    sigma = 10.0
    rho = 28.0
    beta = 8.0 / 3.0
    p = np.array([0.1, 1.0, 1.05], dtype=float)
    points = []

    def f(v):
        x, y, z = v
        return np.array([sigma * (y - x), x * (rho - z) - y, x * y - beta * z])

    for _ in range(n + discard):
        k1 = f(p)
        k2 = f(p + 0.5 * dt * k1)
        k3 = f(p + 0.5 * dt * k2)
        k4 = f(p + dt * k3)
        p = p + (dt / 6.0) * (k1 + 2 * k2 + 2 * k3 + k4)
        points.append(p.copy())

    return np.array(points[discard:])


def nested_rings(n=360, seed=42):
    rng = np.random.default_rng(seed)
    points = []
    labels = []
    for i in range(n):
        ring = i % 3
        angle = 2 * np.pi * (i / n) * 5 + ring * 0.8
        radius = 0.45 + ring * 0.38
        points.append([
            radius * np.cos(angle),
            0.45 * (rng.random() - 0.5) + ring * 0.18,
            radius * np.sin(angle),
        ])
        labels.append(ring)
    return np.array(points), np.array(labels)


def add_feature_lift(x, noise_dims=4, seed=7):
    rng = np.random.default_rng(seed)
    extras = []
    for j in range(noise_dims):
        signal = np.sin((j + 1) * x[:, 0]) + np.cos((j + 2) * x[:, 2])
        extras.append(0.18 * signal + rng.normal(0, 0.13, size=len(x)))
    return np.column_stack([x, *extras])


def neighbor_overlap(x_high, x_low, k=15):
    high = NearestNeighbors(n_neighbors=k + 1).fit(x_high).kneighbors(return_distance=False)[:, 1:]
    low = NearestNeighbors(n_neighbors=k + 1).fit(x_low).kneighbors(return_distance=False)[:, 1:]
    score = 0.0
    for a, b in zip(high, low):
        score += len(set(a).intersection(b)) / k
    return score / len(x_high)


def plot_embedding(embedding, labels, title, path, metric):
    fig, ax = plt.subplots(figsize=(8, 6), dpi=150)
    scatter = ax.scatter(
        embedding[:, 0],
        embedding[:, 1],
        c=labels,
        cmap="viridis",
        s=14,
        alpha=0.86,
        edgecolor="white",
        linewidth=0.25,
    )
    ax.set_title(title)
    ax.set_xlabel("dimension 1")
    ax.set_ylabel("dimension 2")
    ax.text(
        0.02,
        0.02,
        f"kNN overlap: {metric:.3f}",
        transform=ax.transAxes,
        bbox={"facecolor": "white", "edgecolor": "#cbd5e1", "alpha": 0.9},
    )
    fig.colorbar(scatter, ax=ax, fraction=0.046, pad=0.04)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def run_dataset(name, raw, labels, k=15):
    x = StandardScaler().fit_transform(add_feature_lift(raw))
    methods = {
        "pca": PCA(n_components=2, random_state=42),
        "tsne": TSNE(
            n_components=2,
            perplexity=30,
            init="pca",
            learning_rate="auto",
            random_state=42,
            max_iter=1200,
        ),
        "umap": umap.UMAP(
            n_components=2,
            n_neighbors=30,
            min_dist=0.08,
            metric="euclidean",
            random_state=42,
        ),
    }

    rows = []
    embeddings = {}
    for method, reducer in methods.items():
        embedding = reducer.fit_transform(x)
        metric = neighbor_overlap(x, embedding, k=k)
        embeddings[method] = embedding
        rows.append((name, method, metric))
        plot_embedding(embedding, labels, f"{name} - {method.upper()}", OUT / f"{name}_{method}.png", metric)

    np.savez_compressed(OUT / f"{name}_embeddings.npz", labels=labels, **embeddings)
    return rows


def main():
    rows = []
    rings_x, rings_y = nested_rings()
    rows.extend(run_dataset("rings", rings_x, rings_y))

    lorenz_x = lorenz()
    lorenz_y = np.linspace(0, 1, len(lorenz_x))
    rows.extend(run_dataset("lorenz", lorenz_x, lorenz_y))

    lines = [
        "# Canonical Generated Results",
        "",
        "Generated by `python scripts/generate_canonical_results.py` using scikit-learn and umap-learn.",
        "",
        "| Dataset | Method | kNN overlap |",
        "| --- | --- | ---: |",
    ]
    for dataset, method, metric in rows:
        lines.append(f"| {dataset} | {method.upper()} | {metric:.3f} |")
    (OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
